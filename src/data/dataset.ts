export function getRandomDatasetTransaction(excludeId?: string): Transaction {
  const pool = excludeId 
    ? SAMPLE_DATASET.filter((t) => t.id !== excludeId)
    : SAMPLE_DATASET;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex] || SAMPLE_DATASET[0];
}
